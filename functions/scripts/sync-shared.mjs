// Copies the shared calculation code from the web app (src/lib) into functions/src/shared,
// so the server computes leaderboard stats with exactly the same logic as the client.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, '..', '..', 'src', 'lib');
const to = join(here, '..', 'src', 'shared');
mkdirSync(to, { recursive: true });
for (const f of ['calc.ts', 'catalog.ts', 'profanity.ts']) {
  const src = readFileSync(join(from, f), 'utf8').replace(/from '\.\/(\w+)'/g, "from './$1.js'");
  writeFileSync(join(to, f), '// AUTO-GENERATED by functions/scripts/sync-shared.mjs from src/lib — do not edit.\n' + src);
}
console.log('shared code synced');
